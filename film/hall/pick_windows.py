out = {"_note": __doc__.splitlines()[0] + " Generated by film/hall/pick_windows.py; old -> new; speed applies to "
       "the new window. time_lapse: spans crossed (clip seconds, clipped to the window)."}
for sid_id, sid, old, new, speed, why in PICKS:
    ev = json.load(open(os.path.join(TWIN, "scenes", "process_next", f"{sid}_events.json")))
    a, b = new
    assert 0 <= a < b <= ev["seconds"] + 1e-6, (sid_id, new, ev["seconds"])
    tl = [dict(t0=round(max(a, s["t0"]), 2), t1=round(min(b, s["t1"]), 2), factor=s["factor"])
          for s in ev.get("time_lapse", []) if s["t1"] > a and s["t0"] < b]
    rec = dict(sid=sid, old=list(old) if old else None, new=list(new), why=why, clip_seconds=round(ev["seconds"], 2),
               time_lapse=tl, time_lapse_s=round(sum(s["t1"] - s["t0"] for s in tl), 2))
    if speed:
        rec["speed"] = speed
    out[sid_id] = rec
json.dump(out, open(OUT, "w"), indent=1)
for k, r in out.items():
    if k.startswith("_"):
        continue
    print(f"{k:4s} {str(r['old']):10s} -> {str(r['new']):10s} TL {r['time_lapse_s']:5.2f} s "
          f"{[(s['t0'], s['t1'], s['factor']) for s in r['time_lapse']]}")
